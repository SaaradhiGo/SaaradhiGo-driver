/// This app's parsing, against the server's ACTUAL responses.
///
/// WHY NOT A HAND-WRITTEN FIXTURE
/// ------------------------------
/// The rebuilt driver app read `data['access']` and `data['refresh']`. The
/// server sends `token` and `refresh_token`, so login always threw and
/// refresh always failed -- no driver could sign in. Its own tests did not
/// catch it because they built fixtures using the same wrong key names the
/// app used. The tests and the code agreed with each other and both
/// disagreed with the server.
///
/// `test/contracts/auth_contracts.json` is not written by hand. It is
/// generated by `tests/test_auth_contract_capture.py` in the backend, from
/// real responses produced by the real views, and copied here. If a view's
/// shape changes, that file changes and these tests fail -- and nobody can
/// "fix" them by editing a fixture to match the app.
///
/// Regenerate:
///   cd SaaradhiGo-backend && pytest tests/test_auth_contract_capture.py
///   cp contracts/auth_contracts.json ../SaaradhiGo-driver/test/contracts/
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:dio/dio.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:saaradhigo_driver/core/errors/failures.dart';
import 'package:saaradhigo_driver/core/network/api_endpoints.dart';
import 'package:saaradhigo_driver/core/network/dio_client.dart';
import 'package:saaradhigo_driver/core/storage/secure_storage_service.dart';
import 'package:saaradhigo_driver/features/auth/domain/auth_repository.dart';
import 'package:shared_preferences/shared_preferences.dart';

Map<String, dynamic> _loadContract() {
  final file = File('test/contracts/auth_contracts.json');
  if (!file.existsSync()) {
    fail(
      'test/contracts/auth_contracts.json is missing. Generate it by running '
      'the backend test tests/test_auth_contract_capture.py and copying '
      'contracts/auth_contracts.json here.',
    );
  }
  return jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
}

Map<String, dynamic> _endpoint(String name) {
  final endpoints = _loadContract()['endpoints'] as Map<String, dynamic>;
  final entry = endpoints[name];
  if (entry == null) {
    fail(
      'The contract has no entry "$name". Endpoints captured: '
      '${endpoints.keys.join(", ")}',
    );
  }
  return entry as Map<String, dynamic>;
}

Map<String, dynamic> _body(String name) =>
    (_endpoint(name)['body'] as Map).cast<String, dynamic>();

Map<String, dynamic> _data(String name) =>
    (_body(name)['data'] as Map).cast<String, dynamic>();

class _ReplayAdapter implements HttpClientAdapter {
  final List<RequestOptions> requests = [];
  late Future<ResponseBody> Function(RequestOptions options) handler;

  @override
  Future<ResponseBody> fetch(
    RequestOptions options,
    Stream<Uint8List>? requestStream,
    Future<void>? cancelFuture,
  ) async {
    requests.add(options);
    return handler(options);
  }

  @override
  void close({bool force = false}) {}
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  late _ReplayAdapter adapter;
  late AuthRepository repository;

  setUp(() {
    FlutterSecureStorage.setMockInitialValues({});
    SharedPreferences.setMockInitialValues({});
    SecureStorageService.resetSessionRevocationCacheForTests();

    final client = DioClient();
    adapter = _ReplayAdapter();
    client.dio.httpClientAdapter = adapter;
    repository = AuthRepository(client);
  });

  /// Serve a captured response, whatever is asked for.
  void replay(String name) {
    final entry = _endpoint(name);
    adapter.handler = (options) async => ResponseBody.fromString(
      jsonEncode(entry['body']),
      entry['status_code'] as int,
      headers: {
        Headers.contentTypeHeader: [Headers.jsonContentType],
      },
    );
  }

  group('the contract file itself', () {
    test('exists and names its generator', () {
      final contract = _loadContract();
      expect(contract['_README'], contains('GENERATED'));
      expect(contract['endpoints'], isA<Map>());
    });

    test('still says the access token key is `token`, not `access`', () {
      // The exact regression, asserted against the server's own output.
      final data = _data('auth_login_otp');

      expect(data.containsKey('token'), isTrue);
      expect(data.containsKey('refresh_token'), isTrue);
      expect(data.containsKey('access'), isFalse);
      expect(data.containsKey('refresh'), isFalse);
    });

    test('the paths this app posts to are the paths the server captured', () {
      // Binds the constants to the server's own notes, so a renamed route
      // fails here rather than as a 404 on a driver's phone.
      expect(_endpoint('auth_login_otp')['note'], contains(ApiEndpoints.login));
      expect(
        _endpoint('auth_login_email')['note'],
        contains(ApiEndpoints.emailLogin),
      );
      expect(
        _endpoint('auth_refresh')['note'],
        contains(ApiEndpoints.refreshToken),
      );
      expect(_endpoint('auth_logout')['note'], contains(ApiEndpoints.logout));
      expect(
        _endpoint('auth_password_forgot')['note'],
        contains(ApiEndpoints.passwordForgot),
      );
    });
  });

  group('mobile OTP login', () {
    test('parses the real response and stores the real token', () async {
      replay('auth_login_otp');

      await repository.verifyOtp('+919999000001', '100001');

      final expected = _data('auth_login_otp');
      expect(await SecureStorageService.getAccessToken(), expected['token']);
      expect(
        await SecureStorageService.getRefreshToken(),
        expected['refresh_token'],
      );
    });

    test('posts to the captured path', () async {
      replay('auth_login_otp');
      await repository.verifyOtp('+919999000001', '100001');

      expect(adapter.requests.single.path, ApiEndpoints.login);
    });
  });

  group('email + password login', () {
    test('parses the real response and stores the real token', () async {
      replay('auth_login_email');

      await repository.emailLogin(
        email: 'contract-rider@example.test',
        password: 'Cadence-Harbour-74',
      );

      final expected = _data('auth_login_email');
      expect(await SecureStorageService.getAccessToken(), expected['token']);
      expect(
        await SecureStorageService.getRefreshToken(),
        expected['refresh_token'],
      );
      expect(adapter.requests.single.path, ApiEndpoints.emailLogin);
    });

    test('the OTP and email logins have the SAME envelope', () {
      // This is what lets one session layer serve both. If the server ever
      // diverges them, it fails here rather than in production.
      expect(
        _data('auth_login_email').keys.toSet(),
        _data('auth_login_otp').keys.toSet(),
      );
    });

    test('a rejected login is a failure, not a blank session', () async {
      replay('auth_login_email_rejected');

      await expectLater(
        repository.emailLogin(
          email: 'contract-rider@example.test',
          password: 'wrong',
        ),
        throwsA(isA<Failure>()),
      );

      expect(await SecureStorageService.getAccessToken(), isNull);
      expect(await SecureStorageService.getRefreshToken(), isNull);
    });

    test(
      "the driver is shown the server's message, not a generic one",
      () async {
        // DioClient read only `data['message']`, which this API never sends,
        // so every refusal became "Authentication failed" -- which does not
        // tell a driver that their password was wrong.
        replay('auth_login_email_rejected');

        final expected =
            ((_body('auth_login_email_rejected')['error']) as Map)['message'];

        await expectLater(
          repository.emailLogin(email: 'a@b.test', password: 'wrong'),
          throwsA(isA<Failure>().having((f) => f.message, 'message', expected)),
        );
      },
    );

    test('the refusal carries no hint about which part was wrong', () {
      final error = (_body('auth_login_email_rejected')['error'] as Map)
          .cast<String, dynamic>();

      expect(error['message'], 'Invalid email or password.');
      final text = jsonEncode(error).toLowerCase();
      for (final leak in ['no account', 'not found', 'unknown', 'no such']) {
        expect(
          text.contains(leak),
          isFalse,
          reason: 'the refusal leaks "$leak"',
        );
      }
    });

    test('an MFA challenge is surfaced, not swallowed', () async {
      // An operator account signing in through the driver app gets a 401 with
      // a DIFFERENT meaning. The driver app cannot complete it, but it must
      // say what the server said rather than "Authentication failed".
      replay('auth_login_email_mfa_required');

      final expected =
          ((_body('auth_login_email_mfa_required')['error']) as Map)['message'];

      await expectLater(
        repository.emailLogin(email: 'ops@example.test', password: 'correct'),
        throwsA(isA<Failure>().having((f) => f.message, 'message', expected)),
      );
      expect(await SecureStorageService.getAccessToken(), isNull);
    });
  });

  group('token refresh', () {
    test('the captured refresh response carries `token`', () {
      // The second half of the same defect: reading `access` here meant every
      // session died at the access token's lifetime.
      final data = _data('auth_refresh');

      expect(data.containsKey('token'), isTrue);
      expect(data.containsKey('refresh_token'), isTrue);
      expect(data.containsKey('access'), isFalse);
    });

    test(
      'the interceptor refreshes from the captured body and retries',
      () async {
        // Drives the REAL AuthInterceptor: a 401 on a normal call, then the
        // server's own captured refresh response, then the retry.
        FlutterSecureStorage.setMockInitialValues({
          'access_token': 'stale-access-token',
          'refresh_token': 'stored-refresh-token',
        });
        SecureStorageService.resetSessionRevocationCacheForTests();

        final refreshed = _data('auth_refresh');
        var retried = false;

        adapter.handler = (options) async {
          if (options.path == ApiEndpoints.refreshToken) {
            return ResponseBody.fromString(
              jsonEncode(_body('auth_refresh')),
              200,
              headers: {
                Headers.contentTypeHeader: [Headers.jsonContentType],
              },
            );
          }
          if (options.headers['Authorization'] ==
              'Bearer ${refreshed['token']}') {
            retried = true;
            return ResponseBody.fromString(
              jsonEncode({'status': 'success', 'data': {}}),
              200,
              headers: {
                Headers.contentTypeHeader: [Headers.jsonContentType],
              },
            );
          }
          return ResponseBody.fromString(
            jsonEncode({
              'status': 'error',
              'error': {'message': 'expired'},
            }),
            401,
            headers: {
              Headers.contentTypeHeader: [Headers.jsonContentType],
            },
          );
        };

        final client = DioClient();
        client.dio.httpClientAdapter = adapter;
        await client.dio.get<dynamic>(ApiEndpoints.getProfile);

        expect(retried, isTrue, reason: 'the original request was not retried');
        expect(
          await SecureStorageService.getAccessToken(),
          refreshed['token'],
          reason: 'the rotated pair was not stored',
        );
        expect(
          await SecureStorageService.getRefreshToken(),
          refreshed['refresh_token'],
        );
      },
    );
  });

  group('logout', () {
    test('tells the server, then clears locally', () async {
      replay('auth_login_otp');
      await repository.verifyOtp('+919999000001', '100001');
      final storedRefresh = await SecureStorageService.getRefreshToken();
      adapter.requests.clear();

      replay('auth_logout');
      await repository.logout();

      // The server call matters: without it the refresh token stays valid for
      // its full lifetime, so a copy taken off a lost phone still works.
      expect(adapter.requests.single.path, ApiEndpoints.logout);
      expect(
        (adapter.requests.single.data as Map)['refresh_token'],
        storedRefresh,
      );
      expect(await SecureStorageService.getAccessToken(), isNull);
      expect(await SecureStorageService.getRefreshToken(), isNull);
    });

    test('still logs out locally when the server cannot be reached', () async {
      replay('auth_login_otp');
      await repository.verifyOtp('+919999000001', '100001');

      adapter.handler = (options) async => throw DioException.connectionError(
        requestOptions: options,
        reason: 'no network',
      );

      await expectLater(repository.logout(), completes);
      expect(await SecureStorageService.getAccessToken(), isNull);
    });
  });

  group('password reset', () {
    test(
      'forgot-password reveals nothing, and the app repeats it verbatim',
      () async {
        replay('auth_password_forgot');

        final message = await repository.requestPasswordReset(
          'someone@example.test',
        );

        expect(message, _data('auth_password_forgot')['message']);
        expect(
          message.toLowerCase(),
          contains('if that address belongs to an account'),
        );
        expect(adapter.requests.single.path, ApiEndpoints.passwordForgot);
      },
    );
  });

  group('role-based access', () {
    test('a rider token is refused at an operator endpoint', () {
      expect(
        _endpoint('auth_rbac_rider_denied_admin')['status_code'],
        anyOf(401, 403),
      );
    });

    test('an anonymous request is refused', () {
      expect(
        _endpoint('auth_profile_anonymous_denied')['status_code'],
        anyOf(401, 403),
      );
    });
  });
}
