/// This app's parsing, against the server's ACTUAL responses.
///
/// WHY NOT A HAND-WRITTEN FIXTURE
/// ------------------------------
/// This app read `data['access']` and `data['refresh']`. The server sends
/// `token` and `refresh_token`, so login always threw and refresh always
/// failed — no driver could sign in. The app's own tests did not catch it
/// because they built fixtures using the same wrong key names the app used.
/// The tests and the code agreed with each other and both disagreed with the
/// server.
///
/// `test/contracts/auth_contracts.json` is not written by hand. It is
/// generated by `tests/test_auth_contract_capture.py` in the backend, from
/// real responses produced by the real views, and copied here. If a view's
/// shape changes, that file changes and these tests fail — and nobody can
/// "fix" them by editing a fixture to match the app.
///
/// Regenerate: run the backend test, then
///   cp contracts/auth_contracts.json ../SaaradhiGo-driver/test/contracts/
library;

import 'dart:convert';
import 'dart:io';

import 'package:dio/dio.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:saaradhigo_driver/core/network/api_client.dart';
import 'package:saaradhigo_driver/core/storage/local_store.dart';
import 'package:saaradhigo_driver/features/auth/data/auth_repository_impl.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'helpers/fakes.dart';

/// The captured contract, loaded from disk.
Map<String, dynamic> _loadContract() {
  final file = File('test/contracts/auth_contracts.json');
  if (!file.existsSync()) {
    fail(
      'test/contracts/auth_contracts.json is missing. Generate it by running '
      'the backend test tests/test_auth_contract_capture.py and copying '
      'contracts/auth_contracts.json here.',
    );
  }
  return jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
}

Map<String, dynamic> _endpoint(String name) {
  final contract = _loadContract();
  final endpoints = contract['endpoints'] as Map<String, dynamic>;
  final entry = endpoints[name];
  if (entry == null) {
    fail('The contract has no entry "$name". Endpoints captured: '
        '${endpoints.keys.join(", ")}');
  }
  return entry as Map<String, dynamic>;
}

void main() {
  late FakeHttpAdapter adapter;
  late FakeTokenStore tokens;
  late AuthRepositoryImpl repository;
  late ApiClient api;

  setUp(() async {
    SharedPreferences.setMockInitialValues({});
    adapter = FakeHttpAdapter();
    tokens = FakeTokenStore();
    api = ApiClient(tokens, dio: Dio()..httpClientAdapter = adapter);
    repository = AuthRepositoryImpl(api, tokens, await LocalStore.create());
  });

  /// Replay a captured response through the adapter.
  void replay(String name) {
    final entry = _endpoint(name);
    adapter.enqueue(
      status: entry['status_code'] as int,
      body: (entry['body'] as Map).cast<String, dynamic>(),
    );
  }

  group('the contract file itself', () {
    test('exists and names the generator', () {
      final contract = _loadContract();
      expect(contract['_README'], contains('GENERATED'));
      expect(contract['endpoints'], isA<Map>());
    });

    test('still says the access token key is `token`, not `access`', () {
      // The exact regression, asserted against the server's own output.
      final body = _endpoint('auth_login_otp')['body'] as Map;
      final data = (body['data'] as Map).cast<String, dynamic>();

      expect(data.containsKey('token'), isTrue);
      expect(data.containsKey('refresh_token'), isTrue);
      expect(data.containsKey('access'), isFalse);
      expect(data.containsKey('refresh'), isFalse);
    });
  });

  group('mobile OTP login', () {
    test('parses the real response and stores the real token', () async {
      replay('auth_login_otp');

      final user = await repository.verifyOtp(
        phoneNumber: '+919999000001',
        otp: '100001',
      );

      final expected = ((_endpoint('auth_login_otp')['body']
          as Map)['data'] as Map).cast<String, dynamic>();
      expect(tokens.access, expected['token']);
      expect(tokens.refresh, expected['refresh_token']);
      expect(user.phoneNumber, isNotEmpty);
    });
  });

  group('email + password login', () {
    test('parses the real response and stores the real token', () async {
      replay('auth_login_email');

      await repository.emailLogin(
        email: 'contract-rider@example.test',
        password: 'Cadence-Harbour-74',
      );

      final expected = ((_endpoint('auth_login_email')['body']
          as Map)['data'] as Map).cast<String, dynamic>();
      expect(tokens.access, expected['token']);
      expect(tokens.refresh, expected['refresh_token']);
    });

    test('the OTP and email logins have the SAME envelope', () {
      // This is what lets a client swap one for the other. If the server ever
      // diverges them, this fails here rather than in production.
      final otp = ((_endpoint('auth_login_otp')['body']
          as Map)['data'] as Map).keys.toSet();
      final email = ((_endpoint('auth_login_email')['body']
          as Map)['data'] as Map).keys.toSet();
      expect(email, otp);
    });

    test('a rejected login is surfaced as a failure, not a blank session',
        () async {
      replay('auth_login_email_rejected');

      await expectLater(
        repository.emailLogin(
          email: 'contract-rider@example.test',
          password: 'wrong',
        ),
        throwsA(anything),
      );
      expect(tokens.access, isNull);
    });

    test('the refusal carries no hint about which part was wrong', () {
      final body = _endpoint('auth_login_email_rejected')['body'] as Map;
      final error = (body['error'] as Map).cast<String, dynamic>();

      expect(error['message'], 'Invalid email or password.');
      final text = jsonEncode(error).toLowerCase();
      for (final leak in ['no account', 'not found', 'unknown', 'no such']) {
        expect(text.contains(leak), isFalse,
            reason: 'the refusal leaks "$leak"');
      }
    });
  });

  group('token refresh', () {
    test('the captured refresh response carries `token`', () {
      // The second half of the same defect: reading `access` here meant every
      // session died at the 15-minute access-token lifetime.
      final data = ((_endpoint('auth_refresh')['body'] as Map)['data'] as Map)
          .cast<String, dynamic>();

      expect(data.containsKey('token'), isTrue);
      expect(data.containsKey('access'), isFalse);

      // And this app's own reader agrees with it.
      final pair = readTokenPair(data);
      expect(pair.access, data['token']);
      expect(pair.refresh, data['refresh_token']);
    });
  });

  group('role-based access', () {
    test('a rider token is refused at an operator endpoint', () {
      final entry = _endpoint('auth_rbac_rider_denied_admin');
      expect(entry['status_code'], anyOf(401, 403));
    });

    test('an anonymous request is refused', () {
      final entry = _endpoint('auth_profile_anonymous_denied');
      expect(entry['status_code'], anyOf(401, 403));
    });
  });

  group('password reset', () {
    test('forgot-password reveals nothing in its body', () {
      final body = _endpoint('auth_password_forgot')['body'] as Map;
      final message =
          ((body['data'] as Map)['message'] as String).toLowerCase();

      // The server returns the identical body for a known and an unknown
      // address -- asserted on the server side. Here we check the app would
      // have nothing to branch on even if it wanted to.
      expect(message, contains('if that address belongs to an account'));
    });
  });
}
